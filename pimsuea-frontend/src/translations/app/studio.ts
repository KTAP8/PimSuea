export function getReferralLabel(lang: Language, value: string): string {
  const map: Record<string, { th: string; en: string }> = {
    instagram: { th: 'Instagram', en: 'Instagram' },
    tiktok: { th: 'TikTok', en: 'TikTok' },
    search: { th: 'ค้นหาออนไลน์', en: 'Online search' },
    ai_assistant: { th: 'AI assistant (ChatGPT, Gemini, Claude, Perplexity)', en: 'AI assistant (ChatGPT, Gemini, Claude, Perplexity)' },
    word_of_mouth: { th: 'เพื่อนแนะนำ', en: 'Friend referral' },
    other: { th: 'อื่น ๆ', en: 'Other' },
  };
  return map[value]?.[lang] ?? value;
}

export function getAiToolLabel(lang: Language, value: string): string {
  const labels: Record<string, string> = {
    chatgpt: 'ChatGPT',
    gemini: 'Gemini',
    claude: 'Claude',
    perplexity: 'Perplexity',
    other: lang === 'en' ? 'Other' : 'อื่น ๆ',
  };
  return labels[value] ?? value;
}
