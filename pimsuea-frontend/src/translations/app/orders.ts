export const ordersTranslations: Record<Language, typeof th> = { th, en };

const STATUS_COLORS: Record<string, string> = {
  pending_payment: 'bg-yellow-100 text-yellow-800',
  pending: 'bg-blue-50 text-blue-800',
  paid_processing: 'bg-blue-100 text-blue-800',
  printing: 'bg-blue-100 text-blue-800',
  shipped: 'bg-purple-100 text-purple-800',
  delivered: 'bg-green-100 text-green-800',
  cancelled: 'bg-red-100 text-red-800',
};

export function orderStatusLabels(lang: Language): Record<string, string> {
  const labels =
    lang === 'en'
      ? {
          pending_payment: 'Awaiting payment',
          pending: 'Pending',
          paid_processing: 'Paid & in production',
          printing: 'Printing',
          shipped: 'Shipped',
          delivered: 'Delivered',
          cancelled: 'Cancelled',
        }
      : {
          pending_payment: 'รอชำระเงิน',
          pending: 'รอดำเนินการ',
          paid_processing: 'ชำระแล้ว & กำลังผลิต',
          printing: 'กำลังพิมพ์',
          shipped: 'จัดส่งแล้ว',
          delivered: 'ส่งถึงปลายทาง',
          cancelled: 'ยกเลิก',
        };

  return labels;
}

export function getOrderStatusInfo(
  lang: Language,
  status: string,
): { label: string; color: string } {
  const labels = orderStatusLabels(lang);
  return {
    label: labels[status] ?? status,
    color: STATUS_COLORS[status] ?? 'bg-gray-100 text-gray-800',
  };
}
